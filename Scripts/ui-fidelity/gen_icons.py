#!/usr/bin/env python3
"""Generate ZEngine/ZEngine/UI/ZUIIcons.h from the Lucide icon font metadata.

  gen_icons.py [lucide-info.json] [output header]

Edit ICONS to add an icon: names are Lucide icon names (kebab-case), exactly as they appear on
the Figma nodes. The order here is the icon id order, so append new icons at the end of a group.
"""
import json, os, sys

ICONS = [
    # editor chrome and panels (Figma frame 3:2503)
    "chevron-down", "chevron-right", "chevron-left", "eye", "box", "minus", "square", "x", "folder",
    "folder-open", "ellipsis", "rotate-ccw", "rotate-cw", "rotate-3d", "search", "map", "plus",
    "list-filter", "save", "mouse-pointer-2", "code", "settings", "sun", "sun-dim", "cloud-sun",
    "sliders-horizontal", "clapperboard", "play", "pause", "git-branch", "menu", "move", "scaling",
    "globe", "grid-3x3", "grid-2x2", "maximize", "camera", "upload", "workflow", "list-tree",
    "lock-open", "arrow-left-right", "circle", "panel-bottom", "terminal", "circle-check",
    # extra icons used by the tool designs
    "folder-plus", "check", "lock", "layers", "image", "undo-2", "house", "triangle-alert", "ruler", "magnet", "hexagon",
]

def pascal(name):
    return "".join(p.capitalize() for p in name.replace("-", " ").split()).replace("3d", "3D").replace("3x3", "3x3")

def main():
    here = os.path.dirname(os.path.abspath(__file__))
    info_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "lucide-info.json")
    out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "..", "..", "ZEngine", "ZEngine", "UI", "ZUIIcons.h")
    info = json.load(open(info_path))
    rows = []
    for name in ICONS:
        if name not in info:
            sys.exit(f"unknown Lucide icon: {name}")
        rows.append((name, pascal(name), int(info[name]["encodedCode"].lstrip("\\"), 16)))
    lines = [
        "#pragma once",
        "#include <cstdint>",
        "",
        "// GENERATED by Scripts/ui-fidelity/gen_icons.py from the Lucide icon font (ISC licence).",
        "// Do not edit by hand: add the Lucide name to ICONS in the script and regenerate.",
        "",
        "namespace ZEngine::UI",
        "{",
        "    /// @brief Icon ids; the value indexes ZUIFontAtlas::Icon->Glyphs.",
        "    enum class ZUIIcon : uint16_t",
        "    {",
    ]
    for i, (name, p, cp) in enumerate(rows):
        lines.append(f"        {p} = {i}, ///< lucide:{name}")
    lines += [
        f"        Count = {len(rows)}",
        "    };",
        "",
        "    /// @brief Unicode codepoint of each icon in lucide.ttf, indexed by ZUIIcon.",
        "    inline constexpr uint32_t kZUIIconCodepoints[] = {",
    ]
    for name, p, cp in rows:
        lines.append(f"        0x{cp:04X}, // {name}")
    lines += ["    };", "", "} // namespace ZEngine::UI", ""]
    open(out_path, "w").write("\n".join(lines))
    print(f"wrote {len(rows)} icons -> {os.path.normpath(out_path)}")

if __name__ == "__main__":
    main()
